#!/usr/bin/env python3
"""Aceitação da Fatia 3, item 4 (Relatórios, Figma 05 + toast 10:212): conteúdo verbatim, toast, aviso do PDF, toggles.
Pré-requisito: docker compose up; pip install playwright (usa o Chrome do sistema).
Uso: python3 scripts/check_fatia3_relatorios_ui.py <pasta para os prints>"""
import sys
from playwright.sync_api import sync_playwright, expect
S = sys.argv[1]
with sync_playwright() as p:
    b = p.chromium.launch(channel="chrome")
    ctx = b.new_context(viewport={"width": 1440, "height": 1064})
    ctx.add_init_script("window.print = () => { window.__printed = true }")
    pg = ctx.new_page()
    errs = []
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto("http://localhost:5173/")
    pg.get_by_role("button", name="Relatórios").click()
    expect(pg).to_have_url("http://localhost:5173/relatorios")
    expect(pg.locator(".title-plate")).to_contain_text("Relatórios periódicos para concessionárias, anunciantes e gestão pública")
    kpi = pg.locator(".kpi-strip")
    for t in ["14", "3 a mais que julho", "de 14 no mês", "2 campanhas em veiculação", "Seg 07h"]:
        expect(kpi).to_contain_text(t)
    rows = pg.locator(".rl-table tbody tr")
    expect(rows).to_have_count(5)
    expect(rows.first).to_contain_text("Comprovação de campanha · Marca Aurora")
    expect(pg.locator(".rl-table .pill--normal")).to_have_count(3)
    expect(pg.locator(".rl-table .pill--destaque")).to_have_count(2)
    sw = pg.get_by_role("switch")
    expect(sw).to_have_count(4)
    expect(sw.nth(3)).to_have_attribute("aria-checked", "false")
    expect(pg.locator(".rl-content li")).to_have_count(4)
    expect(pg.locator(".rl-foot")).to_contain_text("simulação para validação (Sprint 2)")
    pg.screenshot(path=f"{S}/relatorios.png")
    print("ok: título, KPIs, 5 relatórios recentes, agendamentos, conteúdo, rodapé §8.1")
    sw.nth(3).click()
    expect(sw.nth(3)).to_have_attribute("aria-checked", "true")
    print("ok: toggle de agendamento alterna")
    pg.get_by_role("button", name="Gerar relatório").click()
    dlg = pg.get_by_role("dialog")
    expect(dlg).to_contain_text("Gerar relatório")
    dlg.get_by_role("button", name="Mensal").click()
    dlg.get_by_label("Destinatário").select_option("Gestão pública (fiscalização)")
    dlg.get_by_role("button", name="Gerar", exact=True).click()
    expect(rows).to_have_count(6)
    expect(rows.first).to_contain_text("Relatório mensal · Gestão pública (fiscalização)")
    expect(rows.first.locator(".pill--destaque")).to_contain_text("Em geração")
    expect(rows.first.locator(".pill--normal")).to_contain_text("Auditado", timeout=6000)
    expect(pg.locator(".rl-toast")).to_contain_text("Relatório gerado")
    expect(pg.locator(".rl-toast")).to_contain_text("PDF auditado pronto para enviar a Gestão pública (fiscalização)")
    expect(kpi).to_contain_text("15")
    pg.screenshot(path=f"{S}/relatorios-toast.png")
    print("ok: Gerar relatório -> diálogo (tipo, destinatário) -> linha Em geração -> Auditado + toast do Figma; KPI 15")
    with pg.expect_popup() as pop:
        rows.first.get_by_role("button", name="Baixar PDF").click()
    rp = pop.value
    expect(rp.locator(".rp-head")).to_contain_text("Relatório mensal · Gestão pública (fiscalização)")
    expect(rp.locator(".rp-head")).to_contain_text("agosto (03/08 – 30/08)")
    expect(rp.locator(".rp-sec")).to_have_count(4)
    expect(rp.locator(".rp-sec").nth(2)).to_contain_text("268")
    rp.wait_for_function("window.__printed === true")
    rp.screenshot(path=f"{S}/relatorio-mensal.png", full_page=True)
    rp.close()
    print("ok: Baixar PDF abre o relatório mensal (4 seções, 268 envios) e chama a impressão")
    with pg.expect_popup() as pop:
        rows.nth(1).get_by_role("button", name="Baixar PDF").click()
    expect(pop.value.locator(".rp-sec")).to_have_count(3)
    expect(pop.value.locator(".rp-head")).to_contain_text("Marca Aurora")
    pop.value.close()
    for tipo, secs, txt in [("diario", 4, "Sex 28/08"), ("semanal", 4, "24/08 – 30/08")]:
        rp = ctx.new_page()
        rp.on("pageerror", lambda e: errs.append(str(e)))
        rp.goto(f"http://localhost:5173/relatorios/ver?tipo={tipo}")
        expect(rp.locator(".rp-sec")).to_have_count(secs)
        expect(rp.locator(".rp-head")).to_contain_text(txt)
        rp.screenshot(path=f"{S}/relatorio-{tipo}.png", full_page=True)
        rp.close()
    print("ok: relatórios diário (Sex 28/08) e semanal abrem com as 4 seções")
    rows.nth(5).get_by_role("button", name="Baixar PDF").click()
    expect(pg.get_by_role("status")).to_contain_text("em rascunho")
    print("ok: campanha abre o relatório de comprovação; rascunho avisa que ainda não tem PDF")
    print("erros de página:", errs)
    assert not errs
    b.close()
